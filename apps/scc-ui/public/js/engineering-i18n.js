export function describeEngineeringError(error) {
  const code = error?.code ?? error?.error?.code ?? "SCC-UI-UNKNOWN";
  const message = error?.message ?? error?.error?.message ?? "Unknown error";
  const diagnostic = error?.details?.diagnostic ?? error?.error?.details?.diagnostic;
  if (diagnostic) {
    const localeKey = locale === "zh-CN" ? "zh-CN" : "en";
    const explanation = diagnostic.explanation?.[localeKey];
    const recovery = diagnostic.recovery?.[localeKey];
    return locale === "zh-CN"
      ? `${code}：${explanation ?? "工程操作未完成。"} ${recovery ?? "检查原始错误后重试。"} 原始信息：${diagnostic.original_message ?? message}`
      : `${code}: ${explanation ?? message} ${recovery ?? "Review the actual model state before retrying."}`;
  }
  if (locale !== "zh-CN") return `${code}: ${message}`;
  const [explanation, action] = guidance[code] ?? ["工程操作未完成。", "检查原始错误信息、参数和模型状态后重试。"];
  return `${code}：${explanation} ${action} 原始信息：${message}`;
}
