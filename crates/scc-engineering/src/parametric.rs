/// A single stable edge intent. Runtime OCP Edge objects and indices are never
/// persisted in EngineeringModel.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct EdgeReference {
    pub source_feature_id: FeatureId,
    pub selector: SemanticEdgeSelector,
    #[serde(default)]
    pub qualifier: SemanticEdgeQualifier,
}

impl EdgeReference {
    pub fn validate(&self) -> Result<(), EngineeringError> {
        crate::validate_identifier("edge source feature id", &self.source_feature_id.0)?;
        let q = self.qualifier;
        if !q.tolerance_mm.is_finite()
            || q.tolerance_mm <= 0.0
            || q.radius_mm
                .is_some_and(|value| !value.is_finite() || value <= 0.0)
            || q.length_mm
                .is_some_and(|value| !value.is_finite() || value <= 0.0)
            || q.midpoint.is_some_and(|point| {
                ![point.x, point.y, point.z]
                    .iter()
                    .all(|value| value.is_finite())
            })
        {
            return Err(invalid_feature(
                "INVALID_EDGE_REFERENCE",
                "edge geometric qualifiers must be finite and positive",
            ));
        }
        match &self.selector {
            SemanticEdgeSelector::ProfileBoundary { entity_id, .. }
            | SemanticEdgeSelector::PocketEntrance { entity_id }
            | SemanticEdgeSelector::RevolveProfileVertex { entity_id, .. } => {
                crate::validate_identifier("sketch entity id", &entity_id.0)
            }
            SemanticEdgeSelector::HoleEntrance | SemanticEdgeSelector::HoleExit => Ok(()),
            SemanticEdgeSelector::BetweenFaces { first, second }
            | SemanticEdgeSelector::Convex { first, second }
            | SemanticEdgeSelector::Concave { first, second } => {
                validate_semantic_face_reference(first)?;
                validate_semantic_face_reference(second)?;
                if first == second {
                    return Err(invalid_feature(
                        "INVALID_EDGE_REFERENCE",
                        "an edge adjacency requires two distinct semantic faces",
                    ));
                }
                Ok(())
            }
            SemanticEdgeSelector::BetweenGeneratedFaces { first, second } => {
                first.validate()?;
                second.validate()?;
                if first == second
                    || first.source_feature_id != self.source_feature_id
                    || second.source_feature_id != self.source_feature_id
                {
                    return Err(invalid_feature("INVALID_EDGE_REFERENCE", "generated face adjacency must name two distinct roles from the edge source feature"));
                }
                Ok(())
            }
        }
    }

    pub fn referenced_features(&self) -> Vec<&FeatureId> {
        let mut refs = vec![&self.source_feature_id];
        match &self.selector {
            SemanticEdgeSelector::BetweenFaces { first, second }
            | SemanticEdgeSelector::Convex { first, second }
            | SemanticEdgeSelector::Concave { first, second } => {
                refs.push(&first.source_feature_id);
                refs.push(&second.source_feature_id);
            }
            SemanticEdgeSelector::BetweenGeneratedFaces { first, second } => {
                refs.push(&first.source_feature_id);
                refs.push(&second.source_feature_id);
            }
            _ => {}
        }
        refs
    }
}

fn validate_semantic_face_reference(
    reference: &SemanticPlanarFaceReference,
) -> Result<(), EngineeringError> {
    crate::validate_identifier("face source feature id", &reference.source_feature_id.0)?;
    reference.qualifier.validate(reference.selector)
}

fn validate_edge_treatment(
    edge_refs: &[EdgeReference],
    code: &'static str,
    what: &'static str,
    value: f64,
) -> Result<(), EngineeringError> {
    if !value.is_finite() || value <= 0.0 {
        return Err(invalid_feature(
            code,
            format!("{what} must be finite and greater than zero"),
        ));
    }
    if edge_refs.is_empty() {
        return Err(invalid_feature(
            code,
            "at least one semantic edge reference is required",
        ));
    }
    for (index, reference) in edge_refs.iter().enumerate() {
        reference.validate()?;
        if edge_refs[..index].contains(reference) {
            return Err(invalid_feature(
                "DUPLICATE_EDGE_REFERENCE",
                "edge references must be unique",
            ));
        }
    }
    Ok(())
}

