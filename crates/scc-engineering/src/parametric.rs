#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct PlanarFaceQualifier {
    pub normal: Vector3D,
    /// Signed plane offset `dot(normal, point)` in millimetres.
    pub plane_offset: f64,
    pub tolerance: f64,
}

impl PlanarFaceQualifier {
    pub fn validate(self, selector: PlanarFaceSelector) -> Result<(), EngineeringError> {
        let normal = [self.normal.x, self.normal.y, self.normal.z];
        if !normal.iter().all(|value| value.is_finite())
            || !self.plane_offset.is_finite()
            || !self.tolerance.is_finite()
        {
            return Err(EngineeringError::NonFiniteValue {
                what: "planar face qualifier",
            });
        }
        if self.tolerance <= 0.0 || (norm(normal) - 1.0).abs() > 1.0e-8 {
            return Err(invalid_feature(
                "INVALID_FACE_REFERENCE",
                "planar face qualifier must use a unit normal and positive tolerance",
            ));
        }
        let expected = match selector {
            PlanarFaceSelector::Top => [0.0, 0.0, 1.0],
            PlanarFaceSelector::Bottom => [0.0, 0.0, -1.0],
            PlanarFaceSelector::PositiveX => [1.0, 0.0, 0.0],
            PlanarFaceSelector::NegativeX => [-1.0, 0.0, 0.0],
            PlanarFaceSelector::PositiveY => [0.0, 1.0, 0.0],
            PlanarFaceSelector::NegativeY => [0.0, -1.0, 0.0],
        };
        if normal
            .iter()
            .zip(expected)
            .any(|(actual, wanted)| (actual - wanted).abs() > 1.0e-8)
        {
            return Err(invalid_feature(
                "INVALID_FACE_REFERENCE",
                "planar face selector and qualified normal disagree",
            ));
        }
        Ok(())
    }
}

