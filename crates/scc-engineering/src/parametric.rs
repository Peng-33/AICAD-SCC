/// One closed profile loop. A circle is represented by one Circle entity;
/// other loops are ordered connected line/arc curves.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct SketchLoop {
    pub entities: Vec<SketchEntity>,
}

impl SketchLoop {
    pub fn circle(id: impl Into<String>, center: Point2D, radius: f64) -> Self {
        Self {
            entities: vec![SketchEntity {
                id: SketchEntityId(id.into()),
                geometry: SketchCurveGeometry::Circle { center, radius },
            }],
        }
    }

    /// Convert an existing bounded engineering profile into stable sketch
    /// entities. Rounded rectangles, slots, polygons and composite profiles
    /// become their canonical ordered line/arc boundaries.
    pub fn from_profile(id_prefix: &str, profile: &BaseProfile) -> Result<Self, EngineeringError> {
        crate::validate_identifier("sketch entity prefix", id_prefix)?;
        profile.validate()?;
        if let BaseProfile::Circle { center, diameter } = profile {
            let loop_ = Self::circle(format!("{id_prefix}-0000"), *center, *diameter / 2.0);
            loop_.validate()?;
            return Ok(loop_);
        }
        let segments = profile.segments()?;
        Self::from_segments(id_prefix, &segments)
    }

    pub fn from_segments(
        id_prefix: &str,
        segments: &[ProfileSegment],
    ) -> Result<Self, EngineeringError> {
        crate::validate_identifier("sketch entity prefix", id_prefix)?;
        let mut entities = Vec::with_capacity(segments.len());
        for (index, segment) in segments.iter().enumerate() {
            let id = SketchEntityId(format!("{id_prefix}-{index:04}"));
            crate::validate_identifier("sketch entity id", &id.0)?;
            let geometry = match segment {
                ProfileSegment::Line { start, end } => SketchCurveGeometry::Line {
                    start: *start,
                    end: *end,
                },
                ProfileSegment::Arc {
                    start,
                    end,
                    center,
                    radius,
                    direction,
                } => SketchCurveGeometry::Arc {
                    start: *start,
                    end: *end,
                    center: *center,
                    radius: *radius,
                    direction: *direction,
                },
            };
            entities.push(SketchEntity { id, geometry });
        }
        let loop_ = Self { entities };
        loop_.validate()?;
        Ok(loop_)
    }

    pub fn rectangle(
        id_prefix: &str,
        center: Point2D,
        width: f64,
        height: f64,
    ) -> Result<Self, EngineeringError> {
        crate::positive("sketch rectangle width", width)?;
        crate::positive("sketch rectangle height", height)?;
        crate::finite_point(center, "sketch rectangle center")?;
        let hx = width / 2.0;
        let hy = height / 2.0;
        let corners = [
            Point2D::new(center.x - hx, center.y - hy),
            Point2D::new(center.x + hx, center.y - hy),
            Point2D::new(center.x + hx, center.y + hy),
            Point2D::new(center.x - hx, center.y + hy),
        ];
        let segments = (0..4)
            .map(|index| ProfileSegment::Line {
                start: corners[index],
                end: corners[(index + 1) % 4],
            })
            .collect::<Vec<_>>();
        Self::from_segments(id_prefix, &segments)
    }

    pub fn validate(&self) -> Result<(), EngineeringError> {
        if self.entities.is_empty() {
            return Err(invalid_sketch("profile loop is empty"));
        }
        let mut ids = BTreeSet::new();
        for entity in &self.entities {
            crate::validate_identifier("sketch entity id", &entity.id.0)?;
            if !ids.insert(entity.id.clone()) {
                return Err(invalid_sketch("duplicate sketch entity id"));
            }
            validate_curve(&entity.geometry)?;
        }
        if self.entities.len() == 1
            && matches!(
                self.entities[0].geometry,
                SketchCurveGeometry::Circle { .. }
            )
        {
            return Ok(());
        }
        if self
            .entities
            .iter()
            .any(|entity| matches!(entity.geometry, SketchCurveGeometry::Circle { .. }))
        {
            return Err(invalid_sketch(
                "a Circle loop cannot contain other entities",
            ));
        }
        if self.entities.len() < 2 {
            return Err(invalid_sketch(
                "a non-circular loop needs at least two curves",
            ));
        }
        for index in 0..self.entities.len() {
            let current = curve_endpoints(&self.entities[index].geometry)
                .ok_or_else(|| invalid_sketch("circle must be a single-entity loop"))?;
            let next = curve_endpoints(&self.entities[(index + 1) % self.entities.len()].geometry)
                .ok_or_else(|| invalid_sketch("circle must be a single-entity loop"))?;
            if !same_point(current.1, next.0) {
                return Err(invalid_sketch(
                    "profile loop is open or curves are out of order",
                ));
            }
        }
        Ok(())
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct SketchProfile {
    pub outer: SketchLoop,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub inner_loops: Vec<SketchLoop>,
}

impl SketchProfile {
    pub fn validate(&self) -> Result<(), EngineeringError> {
        self.outer.validate()?;
        let mut ids: BTreeSet<SketchEntityId> = self
            .outer
            .entities
            .iter()
            .map(|entity| entity.id.clone())
            .collect();
        for loop_ in &self.inner_loops {
            loop_.validate()?;
            for entity in &loop_.entities {
                if !ids.insert(entity.id.clone()) {
                    return Err(invalid_sketch(
                        "sketch entity ids must be unique across loops",
                    ));
                }
            }
        }
        Ok(())
    }
}

