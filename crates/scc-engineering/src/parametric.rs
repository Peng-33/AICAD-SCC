impl ParametricFeature {
    pub fn validate(&self) -> Result<(), EngineeringError> {
        match self {
            Self::DatumAxis { definition } => match definition {
                DatumAxisDefinition::Principal { .. } => Ok(()),
                DatumAxisDefinition::ThroughTwoPoints { first, second } => {
                    let first = [first.x, first.y, first.z];
                    let second = [second.x, second.y, second.z];
                    if !first
                        .iter()
                        .chain(second.iter())
                        .all(|value| value.is_finite())
                    {
                        return Err(EngineeringError::NonFiniteValue {
                            what: "datum axis points",
                        });
                    }
                    let delta = [
                        second[0] - first[0],
                        second[1] - first[1],
                        second[2] - first[2],
                    ];
                    if !delta.iter().all(|value| value.is_finite()) {
                        return Err(invalid_feature(
                            "INVALID_DATUM_AXIS",
                            "two-point datum axis direction must be finite",
                        ));
                    }
                    if norm(delta) <= LOOP_TOLERANCE_MM {
                        return Err(invalid_feature(
                            "INVALID_DATUM_AXIS",
                            "two-point datum axis requires distinct finite points",
                        ));
                    }
                    Ok(())
                }
            },
            Self::DatumPlane { definition } => match definition {
                DatumPlaneDefinition::Principal { .. } => Ok(()),
                DatumPlaneDefinition::Offset { distance, .. } => {
                    if !distance.is_finite() {
                        return Err(EngineeringError::NonFiniteValue {
                            what: "datum plane offset",
                        });
                    }
                    Ok(())
                }
                DatumPlaneDefinition::PlanarFaceReference { feature, selector } => {
                    crate::validate_identifier("feature id", &feature.0)?;
                    crate::validate_identifier("semantic face selector", selector)
                }
                DatumPlaneDefinition::CustomPlane {
                    origin,
                    normal,
                    x_axis,
                } => {
                    if !origin
                        .iter()
                        .chain(normal)
                        .chain(x_axis)
                        .all(|value| value.is_finite())
                    {
                        return Err(EngineeringError::NonFiniteValue {
                            what: "custom datum plane",
                        });
                    }
                    let normal_length = norm(*normal);
                    let x_length = norm(*x_axis);
                    if normal_length <= LOOP_TOLERANCE_MM
                        || x_length <= LOOP_TOLERANCE_MM
                        || dot(*normal, *x_axis).abs()
                            > LOOP_TOLERANCE_MM * normal_length * x_length
                    {
                        return Err(invalid_sketch(
                            "custom datum axes must be nonzero and orthogonal",
                        ));
                    }
                    Ok(())
                }
            },
            Self::Sketch { support, profile } => {
                validate_plane_reference(support)?;
                if matches!(support, PlaneReference::GeneratedFace { .. }) {
                    return Err(invalid_feature(
                        "UNSUPPORTED_TOPOLOGY_REFERENCE",
                        "generated-face Sketch support is not part of the current contract",
                    ));
                }
                profile.validate()
            }
            Self::Path { support, segments } => validate_path(support, segments),
            Self::Sweep {
                profile,
                path,
                profile_origin,
                orientation: _,
                ..
            } => {
                crate::validate_identifier("sweep profile feature id", &profile.0)?;
                crate::validate_identifier("sweep path feature id", &path.0)?;
                crate::finite_point(*profile_origin, "sweep profile origin")
            }
            Self::Loft { sections, .. } => {
                if !(MIN_LOFT_SECTIONS..=MAX_LOFT_SECTIONS).contains(&sections.len()) {
                    return Err(invalid_feature(
                        "LOFT_SECTION_COUNT_INVALID",
                        format!(
                            "Loft requires {MIN_LOFT_SECTIONS} to {MAX_LOFT_SECTIONS} ordered Sketch references"
                        ),
                    ));
                }
                let mut seen = BTreeSet::new();
                for section in sections {
                    crate::validate_identifier("Loft section Sketch feature id", &section.0)?;
                    if !seen.insert(section) {
                        return Err(invalid_feature(
                            "LOFT_DUPLICATE_SECTION",
                            "Loft section references must be unique",
                        ));
                    }
                }
                Ok(())
            }
            Self::Hole {
                support,
                position,
                diameter,
                termination,
                kind,
                ..
            } => {
                validate_plane_reference(support)?;
                if let PlaneReference::GeneratedFace { reference } = support {
                    if !matches!(
                        reference.selector,
                        GeneratedFaceSelector::SweepStartCap
                            | GeneratedFaceSelector::SweepEndCap
                            | GeneratedFaceSelector::LoftStartCap
                            | GeneratedFaceSelector::LoftEndCap
                    ) {
                        return Err(invalid_feature(
                            "UNSUPPORTED_TOPOLOGY_REFERENCE",
                            "Hole support requires a planar Sweep/Loft cap role",
                        ));
                    }
                }
                crate::finite_point(*position, "hole position")?;
                positive_code("INVALID_HOLE_DIAMETER", "hole diameter", *diameter)?;
                match termination {
                    HoleTermination::ThroughAll => {}
                    HoleTermination::Blind { depth } => {
                        positive_code("INVALID_HOLE_DEPTH", "hole depth", *depth)?
                    }
                }
                match kind {
                    HoleKind::Simple => {}
                    HoleKind::Counterbore {
                        diameter: cb_diameter,
                        depth,
                    } => {
                        positive_code("INVALID_COUNTERBORE", "counterbore diameter", *cb_diameter)?;
                        positive_code("INVALID_COUNTERBORE", "counterbore depth", *depth)?;
                        if *cb_diameter <= *diameter {
                            return Err(invalid_feature(
                                "INVALID_COUNTERBORE",
                                "counterbore diameter must exceed the main bore diameter",
                            ));
                        }
                        if let HoleTermination::Blind { depth: hole_depth } = termination {
                            if *depth > *hole_depth {
                                return Err(invalid_feature(
                                    "INVALID_COUNTERBORE",
                                    "counterbore depth cannot exceed the blind hole depth",
                                ));
                            }
                        }
                    }
                    HoleKind::Countersink {
                        diameter: cs_diameter,
                        included_angle_degrees,
                    } => {
                        positive_code(
                            "INVALID_COUNTERSINK",
                            "countersink mouth diameter",
                            *cs_diameter,
                        )?;
                        if *cs_diameter <= *diameter
                            || !included_angle_degrees.is_finite()
                            || !(0.0 < *included_angle_degrees && *included_angle_degrees < 180.0)
                        {
                            return Err(invalid_feature("INVALID_COUNTERSINK", "countersink needs a mouth diameter larger than the main bore and an included angle between 0 and 180 degrees"));
                        }
                        let depth = (*cs_diameter - *diameter)
                            / (2.0 * (included_angle_degrees.to_radians() / 2.0).tan());
                        if !depth.is_finite() || depth <= 1.0e-7 {
                            return Err(invalid_feature(
                                "INVALID_COUNTERSINK",
                                "derived countersink depth must be finite and exceed OCP tolerance",
                            ));
                        }
                        if let HoleTermination::Blind { depth: hole_depth } = termination {
                            if depth > *hole_depth + 1.0e-8 {
                                return Err(invalid_feature(
                                    "INVALID_COUNTERSINK",
                                    "derived countersink depth cannot exceed blind-hole depth",
                                ));
                            }
                        }
                    }
                }
                Ok(())
            }
            Self::Pattern { definition, .. } => validate_pattern(definition),
            Self::Fillet { edge_refs, radius } => validate_edge_treatment(
                edge_refs,
                "INVALID_FILLET_RADIUS",
                "fillet radius",
                *radius,
            ),
            Self::Chamfer {
                edge_refs,
                distance,
            } => validate_edge_treatment(
                edge_refs,
                "INVALID_CHAMFER_DISTANCE",
                "chamfer distance",
                *distance,
            ),
            Self::Revolve {
                profile,
                axis,
                angle,
                ..
            } => {
                crate::validate_identifier("revolve profile feature id", &profile.0)?;
                match axis {
                    AxisReference::DatumAxis { feature } => {
                        crate::validate_identifier("datum axis feature id", &feature.0)?;
                    }
                }
                if let RevolveAngle::Partial { degrees } = angle {
                    if !degrees.is_finite() || *degrees <= 0.0 || *degrees >= 360.0 {
                        return Err(invalid_feature(
                            "INVALID_REVOLVE_ANGLE",
                            "partial revolve angle must be finite and greater than 0 and less than 360 degrees",
                        ));
                    }
                }
                Ok(())
            }
            Self::Extrude {
                direction, extent, ..
            } => {
                match direction {
                    ExtrudeDirection::Normal { .. } => {}
                    ExtrudeDirection::Vector { value } => {
                        let values = [value.x, value.y, value.z];
                        if !values.iter().all(|v| v.is_finite()) {
                            return Err(EngineeringError::NonFiniteValue {
                                what: "extrude direction",
                            });
                        }
                        if norm(values) <= LOOP_TOLERANCE_MM {
                            return Err(invalid_sketch("extrude direction vector must be nonzero"));
                        }
                    }
                }
                match extent {
                    ExtrudeExtent::Distance { length } => {
                        crate::positive("extrude distance", *length)
                    }
                    ExtrudeExtent::ThroughAll => Ok(()),
                    ExtrudeExtent::Symmetric { length } => {
                        crate::positive("symmetric extrude length", *length)
                    }
                }
            }
        }
    }

    pub fn referenced_features(&self) -> Vec<&FeatureId> {
        match self {
            Self::DatumPlane {
                definition: DatumPlaneDefinition::Offset { base, .. },
            } => match base {
                PlaneReference::Principal { .. } => Vec::new(),
                PlaneReference::Datum { feature } => vec![feature],
                PlaneReference::PlanarFace {
                    source_feature_id, ..
                } => vec![source_feature_id],
                PlaneReference::GeneratedFace { reference } => vec![&reference.source_feature_id],
            },
            Self::DatumPlane {
                definition: DatumPlaneDefinition::PlanarFaceReference { feature, .. },
            } => vec![feature],
            Self::Sketch { support, .. }
            | Self::Path { support, .. }
            | Self::Hole { support, .. } => match support {
                PlaneReference::Datum { feature } => vec![feature],
                PlaneReference::PlanarFace {
                    source_feature_id, ..
                } => vec![source_feature_id],
                PlaneReference::GeneratedFace { reference } => vec![&reference.source_feature_id],
                PlaneReference::Principal { .. } => Vec::new(),
            },
            Self::Sweep { profile, path, .. } => vec![profile, path],
            Self::Loft { sections, .. } => sections.iter().collect(),
            Self::Extrude { profile, .. } => vec![profile],
            Self::Revolve { profile, axis, .. } => match axis {
                AxisReference::DatumAxis { feature } => vec![profile, feature],
            },
            Self::Pattern {
                seed_feature_id,
                definition,
            } => {
                let mut refs = vec![seed_feature_id];
                if let PatternDefinition::ExplicitPlacement {
                    reference_plane, ..
                } = definition
                {
                    match reference_plane {
                        PlaneReference::Principal { .. } => {}
                        PlaneReference::Datum { feature } => refs.push(feature),
                        PlaneReference::PlanarFace {
                            source_feature_id, ..
                        } => refs.push(source_feature_id),
                        PlaneReference::GeneratedFace { reference } => {
                            refs.push(&reference.source_feature_id)
                        }
                    }
                }
                refs
            }
            Self::Fillet { edge_refs, .. } | Self::Chamfer { edge_refs, .. } => edge_refs
                .iter()
                .flat_map(EdgeReference::referenced_features)
                .collect(),
            _ => Vec::new(),
        }
    }
}

fn validate_path(
    support: &PlaneReference,
    segments: &[SketchEntity],
) -> Result<(), EngineeringError> {
    validate_plane_reference(support)?;
    if matches!(
        support,
        PlaneReference::PlanarFace { .. } | PlaneReference::GeneratedFace { .. }
    ) {
        return Err(invalid_feature(
            "PATH_UNSUPPORTED_SUPPORT",
            "Path currently requires a principal plane or an explicit DatumPlane support",
        ));
    }
    if segments.is_empty() {
        return Err(invalid_feature(
            "PATH_EMPTY",
            "Path needs at least one Line or Arc segment",
        ));
    }
    let mut ids = BTreeSet::new();
    for entity in segments {
        crate::validate_identifier("path segment id", &entity.id.0)?;
        if !ids.insert(entity.id.clone()) {
            return Err(invalid_feature(
                "PATH_DUPLICATE_SEGMENT_ID",
                "Path segment IDs must be unique",
            ));
        }
        if matches!(entity.geometry, SketchCurveGeometry::Circle { .. }) {
            return Err(invalid_feature(
                "PATH_UNSUPPORTED_CURVE",
                "Path supports Line and Arc segments only",
            ));
        }
        validate_curve(&entity.geometry).map_err(|_| {
            invalid_feature(
                "PATH_DEGENERATE",
                "Path contains a non-finite or degenerate curve",
            )
        })?;
    }
    for pair in segments.windows(2) {
        let current = curve_endpoints(&pair[0].geometry).expect("Path contains no circles");
        let next = curve_endpoints(&pair[1].geometry).expect("Path contains no circles");
        if !same_point(current.1, next.0) {
            return Err(invalid_feature(
                "PATH_DISCONTINUOUS",
                "Path segments must connect in their declared order",
            ));
        }
        let left = curve_tangent(&pair[0].geometry, false).expect("Path contains no circles");
        let right = curve_tangent(&pair[1].geometry, true).expect("Path contains no circles");
        if left[0] * right[0] + left[1] * right[1] < 1.0 - 1.0e-10 {
            return Err(invalid_feature(
                "PATH_NON_TANGENT_JOIN",
                "Path joins must be C1 tangent-continuous; sharp corners are unsupported",
            ));
        }
    }
    if same_point(
        curve_endpoints(&segments[0].geometry)
            .expect("Path contains no circles")
            .0,
        curve_endpoints(&segments[segments.len() - 1].geometry)
            .expect("Path contains no circles")
            .1,
    ) {
        return Err(invalid_feature(
            "PATH_CLOSED_UNSUPPORTED",
            "Path must be open; closed sweeps are unsupported",
        ));
    }
    for first in 0..segments.len() {
        for second in (first + 1)..segments.len() {
            let shared = (second == first + 1).then(|| {
                curve_endpoints(&segments[first].geometry)
                    .expect("Path contains no circles")
                    .1
            });
            let intersections =
                curve_intersections(&segments[first].geometry, &segments[second].geometry);
            if intersections
                .iter()
                .any(|point| shared.is_none_or(|joint| !same_point(*point, joint)))
            {
                return Err(invalid_feature(
                    "PATH_SELF_INTERSECTION",
                    "Path segments cross or overlap away from their declared adjacent join",
                ));
            }
        }
    }
    Ok(())
}

fn curve_tangent(curve: &SketchCurveGeometry, at_start: bool) -> Option<[f64; 2]> {
    match curve {
        SketchCurveGeometry::Line { start, end } => {
            let delta = (end.x - start.x, end.y - start.y);
            let length = delta.0.hypot(delta.1);
            (length > LOOP_TOLERANCE_MM).then_some([delta.0 / length, delta.1 / length])
        }
        SketchCurveGeometry::Arc {
            start,
            end,
            center,
            direction,
            ..
        } => {
            let point = if at_start { *start } else { *end };
            let radial = [point.x - center.x, point.y - center.y];
            let length = radial[0].hypot(radial[1]);
            let sign = match direction {
                crate::feature::ArcDirection::CounterClockwise => 1.0,
                crate::feature::ArcDirection::Clockwise => -1.0,
            };
            (length > LOOP_TOLERANCE_MM)
                .then_some([-sign * radial[1] / length, sign * radial[0] / length])
        }
        SketchCurveGeometry::Circle { .. } => None,
    }
}

fn curve_intersections(first: &SketchCurveGeometry, second: &SketchCurveGeometry) -> Vec<Point2D> {
    match (first, second) {
        (
            SketchCurveGeometry::Line { start: p, end: p2 },
            SketchCurveGeometry::Line { start: q, end: q2 },
        ) => {
            let r = [p2.x - p.x, p2.y - p.y];
            let s = [q2.x - q.x, q2.y - q.y];
            let qp = [q.x - p.x, q.y - p.y];
            let cross = |a: [f64; 2], b: [f64; 2]| a[0] * b[1] - a[1] * b[0];
            let denominator = cross(r, s);
            if denominator.abs() > 1.0e-12 {
                let t = cross(qp, s) / denominator;
                let u = cross(qp, r) / denominator;
                if (-1.0e-10..=1.0 + 1.0e-10).contains(&t)
                    && (-1.0e-10..=1.0 + 1.0e-10).contains(&u)
                {
                    vec![Point2D::new(p.x + t * r[0], p.y + t * r[1])]
                } else {
                    Vec::new()
                }
            } else if cross(qp, r).abs() <= 1.0e-10 {
                [*p, *p2, *q, *q2]
                    .into_iter()
                    .filter(|point| {
                        point_on_line(*point, *p, *p2) && point_on_line(*point, *q, *q2)
                    })
                    .collect()
            } else {
                Vec::new()
            }
        }
        (SketchCurveGeometry::Line { .. }, SketchCurveGeometry::Arc { .. }) => {
            line_arc_intersections(first, second)
        }
        (SketchCurveGeometry::Arc { .. }, SketchCurveGeometry::Line { .. }) => {
            line_arc_intersections(second, first)
        }
        (
            SketchCurveGeometry::Arc {
                start: first_start,
                end: first_end,
                center: first_center,
                radius: first_radius,
                ..
            },
            SketchCurveGeometry::Arc {
                start: second_start,
                end: second_end,
                center: second_center,
                radius: second_radius,
                ..
            },
        ) => {
            let intersections = arc_arc_intersections(first, second);
            if !intersections.is_empty()
                || distance(*first_center, *second_center) > LOOP_TOLERANCE_MM
                || (first_radius - second_radius).abs() > LOOP_TOLERANCE_MM
            {
                intersections
            } else {
                // Coincident arcs overlap along a curve, so the circle-circle
                // intersection solver intentionally has no isolated roots.
                // Their shared endpoints are still enough to distinguish a
                // legal adjacent join from overlap or a self-touch elsewhere.
                [*first_start, *first_end, *second_start, *second_end]
                    .into_iter()
                    .filter(|point| {
                        arc_contains_point(first, *point) && arc_contains_point(second, *point)
                    })
                    .fold(Vec::new(), |mut unique, point| {
                        if !unique.iter().any(|existing| same_point(*existing, point)) {
                            unique.push(point);
                        }
                        unique
                    })
            }
        }
        _ => Vec::new(),
    }
}

fn point_on_line(point: Point2D, start: Point2D, end: Point2D) -> bool {
    let dx = end.x - start.x;
    let dy = end.y - start.y;
    let length2 = dx * dx + dy * dy;
    if length2 <= LOOP_TOLERANCE_MM * LOOP_TOLERANCE_MM {
        return same_point(point, start);
    }
    let t = ((point.x - start.x) * dx + (point.y - start.y) * dy) / length2;
    let closest = Point2D::new(start.x + t * dx, start.y + t * dy);
    (-1.0e-10..=1.0 + 1.0e-10).contains(&t) && same_point(point, closest)
}

fn arc_contains_point(curve: &SketchCurveGeometry, point: Point2D) -> bool {
    let SketchCurveGeometry::Arc {
        start,
        end,
        center,
        direction,
        ..
    } = curve
    else {
        return false;
    };
    let angle = |p: Point2D| (p.y - center.y).atan2(p.x - center.x);
    let tau = std::f64::consts::TAU;
    let a0 = angle(*start);
    let a1 = angle(*end);
    let ap = angle(point);
    let (sweep, offset) = match direction {
        crate::feature::ArcDirection::CounterClockwise => {
            ((a1 - a0).rem_euclid(tau), (ap - a0).rem_euclid(tau))
        }
        crate::feature::ArcDirection::Clockwise => {
            ((a0 - a1).rem_euclid(tau), (a0 - ap).rem_euclid(tau))
        }
    };
    offset <= sweep + 1.0e-10
}

fn line_arc_intersections(line: &SketchCurveGeometry, arc: &SketchCurveGeometry) -> Vec<Point2D> {
    let (SketchCurveGeometry::Line { start, end }, SketchCurveGeometry::Arc { center, radius, .. }) =
        (line, arc)
    else {
        return Vec::new();
    };
    let dx = end.x - start.x;
    let dy = end.y - start.y;
    let fx = start.x - center.x;
    let fy = start.y - center.y;
    let a = dx * dx + dy * dy;
    let b = 2.0 * (fx * dx + fy * dy);
    let c = fx * fx + fy * fy - radius * radius;
    let discriminant = b * b - 4.0 * a * c;
    if discriminant < -1.0e-10 {
        return Vec::new();
    }
    let root = discriminant.max(0.0).sqrt();
    [(-b - root) / (2.0 * a), (-b + root) / (2.0 * a)]
        .into_iter()
        .filter(|t| (-1.0e-10..=1.0 + 1.0e-10).contains(t))
        .map(|t| Point2D::new(start.x + t * dx, start.y + t * dy))
        .filter(|point| arc_contains_point(arc, *point))
        .collect()
}

fn arc_arc_intersections(
    first: &SketchCurveGeometry,
    second: &SketchCurveGeometry,
) -> Vec<Point2D> {
    let (
        SketchCurveGeometry::Arc {
            start: _,
            end: _,
            center: c1,
            radius: r1,
            ..
        },
        SketchCurveGeometry::Arc {
            start: _,
            end: _,
            center: c2,
            radius: r2,
            ..
        },
    ) = (first, second)
    else {
        return Vec::new();
    };
    let dx = c2.x - c1.x;
    let dy = c2.y - c1.y;
    let d = dx.hypot(dy);
    if d <= LOOP_TOLERANCE_MM && (r1 - r2).abs() <= LOOP_TOLERANCE_MM {
        let candidates = match (first, second) {
            (
                SketchCurveGeometry::Arc {
                    start: a, end: b, ..
                },
                SketchCurveGeometry::Arc {
                    start: c, end: e, ..
                },
            ) => [*a, *b, *c, *e],
            _ => unreachable!(),
        };
        return candidates
            .into_iter()
            .filter(|p| arc_contains_point(first, *p) && arc_contains_point(second, *p))
            .collect();
    }
    if d <= LOOP_TOLERANCE_MM
        || d > r1 + r2 + LOOP_TOLERANCE_MM
        || d < (r1 - r2).abs() - LOOP_TOLERANCE_MM
    {
        return Vec::new();
    }
    let a = (r1 * r1 - r2 * r2 + d * d) / (2.0 * d);
    let h2 = r1 * r1 - a * a;
    if h2 < -1.0e-8 {
        return Vec::new();
    }
    let h = h2.max(0.0).sqrt();
    let base_x = c1.x + a * dx / d;
    let base_y = c1.y + a * dy / d;
    let points = [
        Point2D::new(base_x - h * dy / d, base_y + h * dx / d),
        Point2D::new(base_x + h * dy / d, base_y - h * dx / d),
    ];
    points
        .into_iter()
        .filter(|p| arc_contains_point(first, *p) && arc_contains_point(second, *p))
        .collect()
}

fn validate_plane_reference(reference: &PlaneReference) -> Result<(), EngineeringError> {
    match reference {
        PlaneReference::Principal { .. } => Ok(()),
        PlaneReference::Datum { feature } => crate::validate_identifier("feature id", &feature.0),
        PlaneReference::PlanarFace {
            source_feature_id,
            selector,
            qualifier,
        } => {
            crate::validate_identifier("feature id", &source_feature_id.0)?;
            qualifier.validate(*selector)
        }
        PlaneReference::GeneratedFace { reference } => reference.validate(),
    }
}

fn validate_pattern(definition: &PatternDefinition) -> Result<(), EngineeringError> {
    match definition {
        PatternDefinition::Linear {
            direction,
            count,
            spacing,
        } => {
            let values = [direction.x, direction.y, direction.z];
            if !values.iter().all(|value| value.is_finite()) {
                return Err(EngineeringError::NonFiniteValue {
                    what: "linear pattern direction",
                });
            }
            if (norm(values) - 1.0).abs() > 1.0e-8 {
                return Err(invalid_feature(
                    "PATTERN_INVALID_AXIS",
                    "linear pattern direction must be a unit vector",
                ));
            }
            if *count < 2 {
                return Err(invalid_feature(
                    "PATTERN_INVALID_COUNT",
                    "linear pattern count must be at least two",
                ));
            }
            positive_code(
                "PATTERN_INVALID_SPACING",
                "linear pattern spacing",
                *spacing,
            )
        }
        PatternDefinition::Circular {
            axis,
            center,
            count,
            radius,
            start_angle_degrees,
            angular_span_degrees,
        } => {
            let axis = [axis.x, axis.y, axis.z];
            let center = [center.x, center.y, center.z];
            if !axis
                .iter()
                .chain(center.iter())
                .all(|value| value.is_finite())
                || !start_angle_degrees.is_finite()
                || !angular_span_degrees.is_finite()
            {
                return Err(EngineeringError::NonFiniteValue {
                    what: "circular pattern parameters",
                });
            }
            if (norm(axis) - 1.0).abs() > 1.0e-8 {
                return Err(invalid_feature(
                    "PATTERN_INVALID_AXIS",
                    "circular pattern axis must be a unit vector",
                ));
            }
            if *count < 2 {
                return Err(invalid_feature(
                    "PATTERN_INVALID_COUNT",
                    "circular pattern count must be at least two",
                ));
            }
            positive_code(
                "PATTERN_INVALID_SPACING",
                "circular pattern radius",
                *radius,
            )?;
            if !(0.0 < *angular_span_degrees && *angular_span_degrees <= 360.0) {
                return Err(invalid_feature(
                    "PATTERN_INVALID_SPACING",
                    "circular pattern angular span must be in (0, 360] degrees",
                ));
            }
            Ok(())
        }
        PatternDefinition::ExplicitPlacement {
            reference_plane,
            placements,
        } => {
            validate_plane_reference(reference_plane)?;
            if matches!(
                reference_plane,
                PlaneReference::PlanarFace { .. } | PlaneReference::GeneratedFace { .. }
            ) {
                return Err(invalid_feature(
                    "PATTERN_UNSUPPORTED_PLACEMENT_PLANE",
                    "explicit placement currently requires a principal or DatumPlane frame",
                ));
            }
            if placements.is_empty() {
                return Err(invalid_feature(
                    "PATTERN_INVALID_COUNT",
                    "explicit placement requires at least one additional placement",
                ));
            }
            if placements.len() > MAX_EXPLICIT_PATTERN_PLACEMENTS {
                return Err(invalid_feature(
                    "PATTERN_INVALID_COUNT",
                    format!(
                        "explicit placement supports at most {MAX_EXPLICIT_PATTERN_PLACEMENTS} additional placements"
                    ),
                ));
            }
            let mut seen = Vec::<(f64, f64)>::with_capacity(placements.len());
            for placement in placements {
                if !placement.local_u_mm.is_finite() || !placement.local_v_mm.is_finite() {
                    return Err(invalid_feature(
                        "PATTERN_INVALID_PLACEMENT",
                        "explicit local U/V coordinates must be finite millimetres",
                    ));
                }
                if seen.iter().any(|(u, v)| {
                    (placement.local_u_mm - u).hypot(placement.local_v_mm - v) <= 1.0e-8
                }) {
                    return Err(invalid_feature(
                        "PATTERN_DUPLICATE_PLACEMENT",
                        "explicit pattern placements must be unique",
                    ));
                }
                seen.push((placement.local_u_mm, placement.local_v_mm));
            }
            Ok(())
        }
    }
}

fn positive_code(code: &str, what: &'static str, value: f64) -> Result<(), EngineeringError> {
    if !value.is_finite() {
        return Err(EngineeringError::NonFiniteValue { what });
    }
    if value <= 0.0 {
        return Err(invalid_feature(
            code,
            format!("{what} must be finite and positive"),
        ));
    }
    Ok(())
}

fn invalid_feature(code: &str, reason: impl AsRef<str>) -> EngineeringError {
    EngineeringError::ModelValidationFailed {
        message: format!("{code}: {}", reason.as_ref()),
    }
}

pub(crate) fn is_parametric(feature: &crate::feature::EngineeringFeature) -> bool {
    matches!(
        feature,
        crate::feature::EngineeringFeature::Parametric { .. }
    )
}

fn validate_curve(curve: &SketchCurveGeometry) -> Result<(), EngineeringError> {
    match curve {
        SketchCurveGeometry::Line { start, end } => {
            crate::finite_point(*start, "sketch line start")?;
            crate::finite_point(*end, "sketch line end")?;
            if same_point(*start, *end) {
                return Err(invalid_sketch("sketch line has zero length"));
            }
        }
        SketchCurveGeometry::Arc {
            start,
            end,
            center,
            radius,
            ..
        } => {
            crate::finite_point(*start, "sketch arc start")?;
            crate::finite_point(*end, "sketch arc end")?;
            crate::finite_point(*center, "sketch arc center")?;
            crate::positive("sketch arc radius", *radius)?;
            if same_point(*start, *end)
                || (distance(*start, *center) - *radius).abs() > LOOP_TOLERANCE_MM
                || (distance(*end, *center) - *radius).abs() > LOOP_TOLERANCE_MM
            {
                return Err(invalid_sketch(
                    "sketch arc endpoints do not match its radius",
                ));
            }
        }
        SketchCurveGeometry::Circle { center, radius } => {
            crate::finite_point(*center, "sketch circle center")?;
            crate::positive("sketch circle radius", *radius)?;
        }
    }
    Ok(())
}

fn curve_endpoints(curve: &SketchCurveGeometry) -> Option<(Point2D, Point2D)> {
    match curve {
        SketchCurveGeometry::Line { start, end } | SketchCurveGeometry::Arc { start, end, .. } => {
            Some((*start, *end))
        }
        SketchCurveGeometry::Circle { .. } => None,
    }
}

fn same_point(left: Point2D, right: Point2D) -> bool {
    distance(left, right) <= LOOP_TOLERANCE_MM
}

fn distance(left: Point2D, right: Point2D) -> f64 {
    ((left.x - right.x).powi(2) + (left.y - right.y).powi(2)).sqrt()
}

fn norm(value: [f64; 3]) -> f64 {
    value.iter().map(|v| v * v).sum::<f64>().sqrt()
}

fn dot(left: [f64; 3], right: [f64; 3]) -> f64 {
    left.iter().zip(right).map(|(a, b)| a * b).sum()
}

fn invalid_sketch(reason: &str) -> EngineeringError {
    EngineeringError::InvalidProfile {
        reason: reason.to_owned(),
    }
}

