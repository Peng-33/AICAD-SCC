/// Feature role plus optional geometry constraints; never an OCP ordinal.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SemanticGeneratedFaceReference {
    pub source_feature_id: FeatureId,
    pub selector: GeneratedFaceSelector,
    #[serde(default)]
    pub qualifier: SemanticGeneratedFaceQualifier,
}

impl SemanticGeneratedFaceReference {
    pub fn validate(&self) -> Result<(), EngineeringError> {
        crate::validate_identifier(
            "generated face source feature id",
            &self.source_feature_id.0,
        )?;
        match &self.selector {
            GeneratedFaceSelector::SweepStartCap
            | GeneratedFaceSelector::SweepEndCap
            | GeneratedFaceSelector::LoftStartCap
            | GeneratedFaceSelector::LoftEndCap => {}
            GeneratedFaceSelector::SweepLateral { profile_entity_id } => {
                crate::validate_identifier("Sweep profile entity id", &profile_entity_id.0)?
            }
            GeneratedFaceSelector::LoftLateral {
                start_section_id,
                end_section_id,
                start_entity_id,
                end_entity_id,
            } => {
                crate::validate_identifier("Loft start section id", &start_section_id.0)?;
                crate::validate_identifier("Loft end section id", &end_section_id.0)?;
                crate::validate_identifier("Loft start profile entity id", &start_entity_id.0)?;
                crate::validate_identifier("Loft end profile entity id", &end_entity_id.0)?;
                if start_section_id == end_section_id {
                    return Err(invalid_feature(
                        "INVALID_TOPOLOGY_REFERENCE",
                        "Loft lateral reference requires two distinct ordered sections",
                    ));
                }
            }
        }
        let q = self.qualifier;
        let finite_point = |point: Vector3D| {
            [point.x, point.y, point.z]
                .iter()
                .all(|value| value.is_finite())
        };
        if !q.tolerance_mm.is_finite()
            || q.tolerance_mm <= 0.0
            || q.area_mm2
                .is_some_and(|value| !value.is_finite() || value <= 0.0)
            || q.area_tolerance_mm2
                .is_some_and(|value| !value.is_finite() || value <= 0.0)
            || q.normal.is_some_and(|normal| {
                !finite_point(normal) || (norm([normal.x, normal.y, normal.z]) - 1.0).abs() > 1.0e-8
            })
            || q.centroid.is_some_and(|point| !finite_point(point))
        {
            return Err(invalid_feature(
                "INVALID_TOPOLOGY_REFERENCE",
                "generated-face qualifiers and tolerances must be finite and positive",
            ));
        }
        Ok(())
    }
}

